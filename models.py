# The system consists of four core entities: User, Restaurant, Order, and Driver.
# The User initiates orders and stores personal, address, and payment information.
# The Restaurant provides food, maintains operational details, and manages a menu catalog.
# The Order acts as the central transaction, connecting the User, Restaurant, and Driver while tracking order status, contents, and total cost.
# The Driver handles delivery logistics, including availability, location tracking, and vehicle details.


